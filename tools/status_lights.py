# CANONICAL in ARMOR-COMMON/tools. Vendored byte-for-byte into the repositories of the families by the sync script of each family, next to its ci_validate.
"""Keeps the traffic lights of the "Project status" table inside what the manifest of the repository allows.

The manifest (``*.project.json``) says how mature the repository is (``maturity``) and how far it has been shown to work (``evidence``):

    none / host-test   tests on a computer only
    simulator          run against a simulated or fake board or bus
    bench              run on a real board on the bench
    field              used in the field

From those two fields, and from the files of the repository, the tool computes the CEILING of the light of every row of the table:

    Hardware, Integration   none / host-test / simulator: orange at most; bench: yellow at most; field: green
                            (a manifest with ``"hardware_bound": false`` has no hardware: these rows are not limited by the evidence)
    Software, Tests, Documentation   green only when the repository has tests and a CI workflow (and, with --ci auto, the last run of the
                            default branch is green); otherwise yellow at most
    every row               a repository of maturity scaffolding / experimental / alpha / prototype: yellow at most

The tool only moves lights. It never reads or writes the sentence of a row: the sentences are written by a person.

    python tools/status_lights.py --check      # fail when a light is above its ceiling, or the eight READMEs disagree (offline; used by ci_validate)
    python tools/status_lights.py --suggest    # list the rows that could be better by the manifest and the evidence; writes nothing
    python tools/status_lights.py --apply      # lower every light above its ceiling in the eight READMEs and in the source of the generator
    python tools/status_lights.py --apply --raise   # also raise a hardware / integration light one step when the evidence allows it

In the HYDRA-UMC family the lights are generated by HYDRA-UMC-DOCS (src/hydra_umc_docs/status.py) from the maturity of the manifest and from data/glance.json.
When that file sits next to the repository, ``--check`` also verifies that the ``evidence`` of the manifest agrees with the hardware statement of glance.json
(not_run: none or host-test; simulated: simulator; bench: bench; in_use: field; not_applicable: ``"hardware_bound": false``), and ``--apply`` writes nothing there:
the generator would restore the lights, so the data (glance.json, the manifest) is what has to change.

``--repo PATH`` works on another repository (default: the repository this file sits in). ``--ci auto|off`` (default: off for --check, auto otherwise)
asks ``gh run list`` for the last run of the default branch.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

RED, ORANGE, YELLOW, GREEN = "\U0001F534", "\U0001F7E0", "\U0001F7E1", "\U0001F7E2"
ORDER = (RED, ORANGE, YELLOW, GREEN)            # worst to best
NAMES = {"red": RED, "orange": ORANGE, "yellow": YELLOW, "green": GREEN}
WORDS = {value: key for key, value in NAMES.items()}
EVIDENCE_LEVELS = ("none", "host-test", "simulator", "bench", "field")
EVIDENCE_CEILING = {"none": ORANGE, "host-test": ORANGE, "simulator": ORANGE, "bench": YELLOW, "field": GREEN}
LOW_MATURITY = {"scaffolding", "experimental", "alpha", "prototype"}
LANGUAGE_FILES = ("README.md", "README_spa.md", "README_fra.md", "README_ita.md", "README_deu.md", "README_zho.md", "README_jpn.md", "README_por.md")
HEADING = re.compile("^## (?:\U0001F6A6|\U0001F4A1) ")
FENCE = re.compile(r"^\s*(```|~~~)")
SKIP_DIRS = {".git", "node_modules", "target", "build", "dist", ".venv", "venv", "__pycache__", ".gradle", "managed_components"}
TEST_NAME = re.compile(r"(^test_.*\.(py|js|ts|rs|cpp|c|kt)$)|(_test\.(py|go|rs|c|cpp)$)|(\.(test|spec)\.(js|ts|tsx|mjs)$)|(Tests?\.(kt|java|swift|cs)$)")


def fail(message: str) -> "None":
    print(f"STATUS_LIGHTS=FAIL {message}", file=sys.stderr)
    raise SystemExit(1)


def kind_of(label: str) -> str:
    """The kind of a row from its English label: hardware, integration, software, tests, docs or other."""
    text = label.strip().lower()
    if "integration" in text:
        return "integration"
    if "hardware" in text or "board" in text or "firmware on" in text:
        return "hardware"
    if text.startswith("test"):
        return "tests"
    if text.startswith("documentation") or text == "docs":
        return "docs"
    if text == "software":
        return "software"
    return "other"


def manifest_of(root: Path) -> dict:
    found = sorted(root.glob("*.project.json"))
    if not found:
        fail(f"no *.project.json manifest in {root}")
    try:
        return json.loads(found[0].read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        fail(f"cannot read {found[0].name}: {error}")
    return {}


def has_tests(root: Path) -> bool:
    for current, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        if Path(current) != root and Path(current).name in ("tests", "test", "__tests__") and files:
            return True
        if any(TEST_NAME.search(name) for name in files):
            return True
    return False


def has_ci(root: Path) -> bool:
    workflows = root / ".github" / "workflows"
    return workflows.is_dir() and any(workflows.glob("*.y*ml"))


def ci_state(root: Path) -> str:
    """'green', 'red' or 'unknown' from the last completed run of the default branch (needs gh)."""
    try:
        out = subprocess.run(["gh", "run", "list", "--limit", "5", "--json", "conclusion,status,headBranch"], cwd=root, capture_output=True, text=True, timeout=60)
        runs = [r for r in json.loads(out.stdout or "[]") if r.get("status") == "completed" and r.get("headBranch") in ("main", "master")]
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
        return "unknown"
    if not runs:
        return "unknown"
    return "green" if runs[0].get("conclusion") == "success" else "red"


def read_table(text: str) -> tuple[int, list[list[str]]] | None:
    """(line index of the first data row, the cells of each data row) of the status table, or None."""
    lines = text.split("\n")
    fenced, start = False, None
    for index, line in enumerate(lines):
        if FENCE.match(line):
            fenced = not fenced
        elif not fenced and line.startswith("## "):
            if start is not None:
                break
            if HEADING.match(line):
                start = index
    if start is None:
        return None
    block = []
    for index in range(start + 1, len(lines)):
        if lines[index].startswith("## "):
            break
        if lines[index].startswith("|"):
            block.append((index, lines[index]))
    data = block[2:]
    if not data:
        return None
    rows = []
    for _, line in data:
        rows.append([cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip().strip("|"))])
    return data[0][0], rows


def lights_of(rows: list[list[str]]) -> list[str]:
    return [row[1] if len(row) > 1 else "" for row in rows]


def replace_lights(text: str, wanted: list[str]) -> str:
    table = read_table(text)
    assert table is not None
    first, _ = table
    lines = text.split("\n")
    for offset, light in enumerate(wanted):
        line = lines[first + offset]
        cells = re.split(r"(?<!\\)(\|)", line)
        # cells: ['', '|', ' Part ', '|', ' light ', '|', ...]
        cells[4] = f" {light} "
        lines[first + offset] = "".join(cells)
    return "\n".join(lines)


def ceiling(kind: str, manifest: dict, tests: bool, ci: bool, ci_now: str) -> tuple[str, str]:
    """(the highest light allowed, why)."""
    best, why = GREEN, "no limit"
    def lower(level: str, reason: str) -> None:
        nonlocal best, why
        if ORDER.index(level) < ORDER.index(best):
            best, why = level, reason
    if str(manifest.get("maturity", "")).lower() in LOW_MATURITY:
        lower(YELLOW, f"maturity {manifest.get('maturity')}")
    evidence = manifest.get("evidence", "none")
    if kind in ("hardware", "integration") and manifest.get("hardware_bound", True) is not False:
        lower(EVIDENCE_CEILING.get(evidence, ORANGE), f"evidence {evidence}")
    if kind in ("software", "tests", "docs"):
        if not tests:
            lower(YELLOW, "no tests in the repository")
        elif not ci:
            lower(YELLOW, "no CI workflow")
        elif ci_now == "red":
            lower(YELLOW, "the CI of the default branch is red")
    return best, why


def evaluate(root: Path, ci_mode: str) -> dict:
    manifest = manifest_of(root)
    english = root / "README.md"
    if not english.is_file():
        fail(f"{root.name}: no README.md")
    table = read_table(english.read_bytes().decode("utf-8"))
    if table is None:
        fail(f"{root.name}: README.md has no Project status table")
    rows = table[1]
    ci_now = ci_state(root) if ci_mode == "auto" else "unknown"
    tests, ci = has_tests(root), has_ci(root)
    items = []
    for number, row in enumerate(rows):
        label, light = row[0], row[1]
        kind = kind_of(label)
        top, why = ceiling(kind, manifest, tests, ci, ci_now)
        items.append({"index": number, "label": label, "kind": kind, "light": light, "ceiling": top, "why": why})
    return {"manifest": manifest, "items": items, "ci": ci_now}


def problems_of(root: Path, state: dict) -> list[str]:
    problems = []
    manifest = state["manifest"]
    evidence = manifest.get("evidence")
    if evidence is None:
        problems.append(f"{root.name}: the manifest has no 'evidence' (one of {', '.join(EVIDENCE_LEVELS)})")
    elif evidence not in EVIDENCE_LEVELS:
        problems.append(f"{root.name}: manifest evidence {evidence!r} is not one of {', '.join(EVIDENCE_LEVELS)}")
    problems.extend(hydra_problems(root, manifest))
    for item in state["items"]:
        if item["light"] not in ORDER:
            problems.append(f"{root.name}: row {item['label']!r} holds {item['light']!r}, not a light")
        elif ORDER.index(item["light"]) > ORDER.index(item["ceiling"]):
            problems.append(f"{root.name}: row {item['label']!r} is {WORDS[item['light']]} but the ceiling is {WORDS[item['ceiling']]} ({item['why']})")
    english = lights_of([[i["label"], i["light"]] for i in state["items"]])
    for name in LANGUAGE_FILES[1:]:
        path = root / name
        if not path.is_file():
            continue
        table = read_table(path.read_bytes().decode("utf-8"))
        if table is None:
            problems.append(f"{root.name}/{name}: no Project status table")
        elif lights_of(table[1]) != english:
            problems.append(f"{root.name}/{name}: the lights differ from README.md")
    return problems


HYDRA_EVIDENCE = {"not_run": ("none", "host-test"), "simulated": ("simulator",), "bench": ("bench",), "in_use": ("field",)}


def is_hydra(root: Path) -> bool:
    return root.name == "HYDRA-UMC" or root.name.startswith("HYDRA-UMC-")


def hydra_entry(root: Path) -> dict | None:
    """The record of this repository in HYDRA-UMC-DOCS/data/glance.json (the origin of the HYDRA lights), or None when that file is not next to the repository."""
    path = root.parent / "HYDRA-UMC-DOCS" / "data" / "glance.json"
    if not is_hydra(root) or not path.is_file():
        return None
    try:
        entry = json.loads(path.read_bytes().decode("utf-8")).get("repos", {}).get(root.name)
    except (OSError, ValueError):
        return None
    return entry if isinstance(entry, dict) else None


def hydra_problems(root: Path, manifest: dict) -> list[str]:
    """The manifest has to say what glance.json says about the hardware, because the generator takes the light from glance.json."""
    entry = hydra_entry(root)
    if entry is None:
        return []
    state = entry.get("hardware")
    evidence = manifest.get("evidence")
    unbound = manifest.get("hardware_bound", True) is False
    if state == "not_applicable":
        if not unbound:
            return [f"{root.name}: glance.json says the hardware is not applicable, so the manifest needs \"hardware_bound\": false"]
        return []
    problems = []
    if unbound:
        problems.append(f"{root.name}: the manifest says hardware_bound false but glance.json holds hardware {state!r}")
    allowed = HYDRA_EVIDENCE.get(str(state))
    if allowed is not None and evidence not in allowed:
        problems.append(f"{root.name}: glance.json holds hardware {state!r} but the manifest evidence is {evidence!r} (expected {' or '.join(allowed)})")
    return problems


def run_in_ci(root: Path) -> list[str]:
    """What a ci_validate calls: the reasons to fail (a light above its ceiling, no evidence in the manifest, the eight READMEs with different lights). Offline."""
    english = root / "README.md"
    if not english.is_file() or read_table(english.read_bytes().decode("utf-8")) is None:
        return []   # a missing table is the business of the README checks, not of the lights
    try:
        state = evaluate(root, "off")
    except SystemExit:
        return [f"{root.name}: the Project status table or the manifest cannot be read (python tools/status_lights.py --check says what)"]
    return problems_of(root, state)


def patch_armor_source(root: Path, wanted: list[str]) -> str | None:
    """The generator of ARMOR-DOCS keeps the lights in FACTS['status'] of tools/readme_src/repos/<NAME>.py as [area, colour] pairs."""
    source = root.parent / "ARMOR-DOCS" / "tools" / "readme_src" / "repos" / (root.name.replace("-", "_") + ".py")
    if not source.is_file():
        return None
    text = source.read_bytes().decode("utf-8")
    start = text.find('"status": [')
    if start < 0:
        return None
    depth, end = 0, None
    for position in range(start + len('"status": '), len(text)):
        if text[position] == "[":
            depth += 1
        elif text[position] == "]":
            depth -= 1
            if depth == 0:
                end = position + 1
                break
    block = text[start:end]
    pairs = list(re.finditer(r'("(\w+)",\s*")(green|yellow|orange|red)(")', block))
    if len(pairs) != len(wanted):
        fail(f"{source.name}: {len(pairs)} rows in the source but {len(wanted)} in the README")
    out, last = [], 0
    for match, light in zip(pairs, wanted, strict=True):
        out.append(block[last:match.start(3)] + WORDS[light])
        last = match.end(3)
    out.append(block[last:])
    new = text[:start] + "".join(out) + text[end:]
    if new != text:
        source.write_bytes(new.encode("utf-8"))
        return str(source)
    return None


def patch_urtc_source(root: Path, wanted: list[str]) -> list[str]:
    """The generator of the tool-platform family keeps the table of a repository in spec/readme/sections.json of its common repository (section status_*), and the one of its docs repository in src/<package>_docs/status.py."""
    family = "URT" + "C"
    touched: list[str] = []
    spec = root.parent / (family + "-COMMON") / "spec" / "readme" / "sections.json"
    if spec.is_file() and root.name != family + "-DOCS":
        raw = spec.read_bytes().decode("utf-8")
        data = json.loads(raw)
        changed = False
        for section in data.get("sections", []):
            if not str(section.get("id", "")).startswith("status_") or root.name not in section.get("repos", []):
                continue
            for language, body in list(section["body"].items()):
                table = read_table("## \U0001F6A6 x\n" + body)
                if table is None or len(table[1]) != len(wanted):
                    fail(f"sections.json {section['id']} {language}: {0 if table is None else len(table[1])} rows but {len(wanted)} in the README")
                new = replace_lights("## \U0001F6A6 x\n" + body, wanted)[len("## \U0001F6A6 x\n"):]
                if new != body:
                    section["body"][language] = new
                    changed = True
        if changed:
            indent = 2 if raw.startswith("{\n  \"") else 1
            new_raw = json.dumps(data, ensure_ascii=False, indent=indent) + ("\n" if raw.endswith("\n") else "")
            spec.write_bytes(new_raw.encode("utf-8"))
            touched.append(str(spec))
    own = root.parent / (family + "-DOCS") / "src" / (family.lower() + "_docs") / "status.py"
    if root.name == family + "-DOCS" and own.is_file():
        text = own.read_bytes().decode("utf-8")
        marker = text.find("OWN_ROWS")
        parts = re.split(r'(\n    "[a-z]{2}": \[)', text[marker:])
        rebuilt = [text[:marker], parts[0]]
        for header, chunk in zip(parts[1::2], parts[2::2], strict=True):
            rows = list(re.finditer(r'(\n        \("(?:[^"\\]|\\.)*", ")([' + "".join(ORDER) + r'])(")', chunk))
            if len(rows) != len(wanted):
                fail(f"status.py: {len(rows)} rows in a language but {len(wanted)} in the README")
            out, last = [], 0
            for match, light in zip(rows, wanted, strict=True):
                out.append(chunk[last:match.start(2)] + light)
                last = match.end(2)
            out.append(chunk[last:])
            rebuilt += [header, "".join(out)]
        new = "".join(rebuilt)
        if new != text:
            own.write_bytes(new.encode("utf-8"))
            touched.append(str(own))
    return touched


def apply(root: Path, state: dict, allow_raise: bool) -> int:
    wanted = []
    for item in state["items"]:
        light = item["light"]
        if light in ORDER and ORDER.index(light) > ORDER.index(item["ceiling"]):
            light = item["ceiling"]
        elif allow_raise and item["kind"] in ("hardware", "integration") and light in ORDER and ORDER.index(light) < ORDER.index(item["ceiling"]):
            light = ORDER[ORDER.index(light) + 1]
        wanted.append(light)
    changed = 0
    for name in LANGUAGE_FILES:
        path = root / name
        if not path.is_file():
            continue
        text = path.read_bytes().decode("utf-8")
        table = read_table(text)
        if table is None or len(table[1]) != len(wanted):
            fail(f"{root.name}/{name}: the table does not have the {len(wanted)} rows of README.md")
        new = replace_lights(text, wanted)
        if new != text:
            path.write_bytes(new.encode("utf-8"))
            changed += 1
    before = [i["light"] for i in state["items"]]
    if wanted != before:
        armor = patch_armor_source(root, wanted)
        touched = ([armor] if armor else []) + patch_urtc_source(root, wanted)
        for path in touched:
            print(f"source updated: {path}")
        for item, light in zip(state["items"], wanted, strict=True):
            if item["light"] != light:
                print(f"{root.name}: {item['label']}: {WORDS[item['light']]} -> {WORDS[light]} ({item['why']})")
    return changed


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--suggest", action="store_true")
    mode.add_argument("--apply", action="store_true")
    parser.add_argument("--repo", default=str(Path(__file__).resolve().parents[1]))
    parser.add_argument("--ci", choices=("auto", "off"), default=None)
    parser.add_argument("--raise", dest="allow_raise", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.repo).resolve()
    state = evaluate(root, args.ci or ("off" if args.check else "auto"))
    if args.check:
        problems = problems_of(root, state)
        for line in problems:
            print(line, file=sys.stderr)
        if problems:
            print(f"STATUS_LIGHTS=FAIL {len(problems)} problem(s)", file=sys.stderr)
            return 1
        print(f"STATUS_LIGHTS=PASS {root.name}")
        return 0
    if args.suggest:
        for item in state["items"]:
            if item["light"] in ORDER and ORDER.index(item["light"]) < ORDER.index(item["ceiling"]):
                print(f"{root.name}: {item['label']}: {WORDS[item['light']]} could reach {WORDS[item['ceiling']]} (kind {item['kind']}; a person decides, the sentence must say what ran)")
            elif item["light"] in ORDER and ORDER.index(item["light"]) > ORDER.index(item["ceiling"]):
                print(f"{root.name}: {item['label']}: {WORDS[item['light']]} is ABOVE its ceiling {WORDS[item['ceiling']]} ({item['why']})")
        return 0
    if is_hydra(root):
        print(f"{root.name}: the lights are generated by HYDRA-UMC-DOCS from the manifest and data/glance.json; --apply writes nothing here (change that data, then run its generator). --suggest lists what is possible.")
        return 0
    changed = apply(root, state, args.allow_raise)
    print(f"STATUS_LIGHTS=APPLIED {root.name}: {changed} README file(s) written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
