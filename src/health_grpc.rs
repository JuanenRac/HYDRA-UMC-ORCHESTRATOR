//! The health service of the shared contract (`proto/hydra_common.proto`) served over gRPC, so
//! HYDRA-UMC-NODE-HEALING can ask `Check()` and follow `Watch()` instead of polling the HTTP route.
//!
//! Off unless the configuration file turns on `health_grpc.enabled`. It listens on loopback by
//! default; any other address needs a bearer token (the API token of this process or the one
//! named by `health_grpc.token_env`). The state it reports is real: the mission registry must be
//! readable and the global stop must not be engaged for it to say OK. It reads, it never changes
//! anything, and it has no say in the physical stop.
//!
//! Limits: a bounded number of connections, a bounded number of open `Watch()` streams, small
//! messages, HTTP/2 keepalive pings so a vanished client is noticed, and every stream task ends
//! when its client goes away or the server stops.

