pub const NODE_NAME: &str = "HYDRA-UMC-ORCHESTRATOR";
pub const DEFAULT_LISTEN: &str = "127.0.0.1:50114";
pub const DEFAULT_MAX_CONNECTIONS: usize = 16;
pub const DEFAULT_MAX_WATCHERS: usize = 8;
pub const DEFAULT_WATCH_INTERVAL: Duration = Duration::from_secs(5);
pub const DEFAULT_KEEPALIVE: Duration = Duration::from_secs(30);

/// The settings the service runs with (built from the configuration file by `config.rs`).
#[derive(Debug, Clone)]
pub struct HealthGrpcConfig {
    pub listen: SocketAddr,
    /// bearer token every call needs; `None` is only allowed on loopback
    pub token: Option<String>,
    pub max_connections: usize,
    pub max_watchers: usize,
    /// how often a `Watch()` stream repeats the report when nothing changed (the keepalive of the stream)
    pub watch_interval: Duration,
    /// HTTP/2 keepalive ping period; a client that does not answer within the same time is dropped
    pub keepalive: Duration,
}

impl Default for HealthGrpcConfig {
    fn default() -> Self {
        HealthGrpcConfig {
            listen: DEFAULT_LISTEN.parse().expect("a valid default address"),
            token: None,
            max_connections: DEFAULT_MAX_CONNECTIONS,
            max_watchers: DEFAULT_MAX_WATCHERS,
            watch_interval: DEFAULT_WATCH_INTERVAL,
            keepalive: DEFAULT_KEEPALIVE,
        }
    }
}

/// Where the report comes from: called for every `Check()` and on every tick of a `Watch()`.
pub type ReportSource = Arc<dyn Fn() -> HealthReport + Send + Sync>;

fn identity() -> NodeIdentity {
    NodeIdentity {
        name: NODE_NAME.to_string(),
        version: env!("CARGO_PKG_VERSION").to_string(),
        role: "Distributed swarm manager".to_string(),
        family: "orchestration-swarm".to_string(),
        deploy: DeployTarget::Cm5 as i32,
    }
}

/// The real state of the orchestrator: OK only when the mission registry can be read and the
/// global stop is not engaged. A registry that is busy for the moment is not a failure (the
/// answer must never wait on it), a poisoned one is.
pub fn report(registry: &Mutex<MissionRegistry>, stop_engaged: bool) -> HealthReport {
    let mut metrics = std::collections::HashMap::new();
    metrics.insert("global_stop".to_string(), stop_engaged.to_string());
    let (mut state, mut detail) = (HealthState::Ok, "ready".to_string());
    match registry.try_lock() {
        Ok(reg) => {
            let (mut total, mut active, mut unknown) = (0usize, 0usize, 0usize);
            for mission in reg.all() {
                total += 1;
                if !mission.is_terminal() {
                    active += 1;
                }
                if matches!(mission.state, MissionState::Unknown { .. }) {
                    unknown += 1;
                }
            }
            metrics.insert("missions".to_string(), total.to_string());
            metrics.insert("missions_active".to_string(), active.to_string());
            metrics.insert("missions_unknown".to_string(), unknown.to_string());
        }
        Err(TryLockError::WouldBlock) => {
            detail = "ready (the mission registry is busy at this moment)".to_string();
        }
        Err(TryLockError::Poisoned(_)) => {
            state = HealthState::Unhealthy;
            detail = "the mission registry is not usable (a worker panicked while holding it)"
                .to_string();
        }
    }
    if stop_engaged && state == HealthState::Ok {
        state = HealthState::Degraded;
        detail = "the global stop is engaged: no mission moves until it is released".to_string();
    }
    HealthReport {
        identity: Some(identity()),
        state: state as i32,
        detail,
        metrics,
    }
}

struct Service {
    source: ReportSource,
    watchers: Arc<AtomicUsize>,
    max_watchers: usize,
    interval: Duration,
    shutdown: tokio::sync::watch::Receiver<bool>,
}

/// Releases the place of a `Watch()` stream when its task ends, however it ends.
struct WatcherSlot(Arc<AtomicUsize>);

impl Drop for WatcherSlot {
    fn drop(&mut self) {
        self.0.fetch_sub(1, Ordering::SeqCst);
    }
}

#[tonic::async_trait]
impl HealthService for Service {
    async fn check(&self, _request: Request<Empty>) -> Result<Response<HealthReport>, Status> {
        Ok(Response::new((self.source)()))
    }

    type WatchStream = ReceiverStream<Result<HealthReport, Status>>;

    async fn watch(&self, _request: Request<Empty>) -> Result<Response<Self::WatchStream>, Status> {
        if self.watchers.fetch_add(1, Ordering::SeqCst) >= self.max_watchers {
            self.watchers.fetch_sub(1, Ordering::SeqCst);
            return Err(Status::resource_exhausted(
                "too many Watch streams are open",
            ));
        }
        let slot = WatcherSlot(Arc::clone(&self.watchers));
        let (tx, rx) = mpsc::channel(2);
        let source = Arc::clone(&self.source);
        let interval = self.interval;
        let mut shutdown = self.shutdown.clone();
        tokio::spawn(async move {
            let _slot = slot;
            let mut ticker = tokio::time::interval(Duration::from_secs(1).min(interval));
            let mut last: Option<(i32, String)> = None;
            let mut last_sent = tokio::time::Instant::now();
            let mut first = true;
            loop {
                tokio::select! {
                    _ = tx.closed() => break,
                    _ = shutdown.changed() => break,
                    _ = ticker.tick() => {}
                }
                let current = source();
                let key = (current.state, current.detail.clone());
                let due = first || last.as_ref() != Some(&key) || last_sent.elapsed() >= interval;
                if !due {
                    continue;
                }
                first = false;
                last = Some(key);
                last_sent = tokio::time::Instant::now();
                // a client that stopped reading must not hold this task: the send gives up with the stream
                tokio::select! {
                    sent = tx.send(Ok(current)) => if sent.is_err() { break },
                    _ = shutdown.changed() => break,
                }
            }
        });
        Ok(Response::new(ReceiverStream::new(rx)))
    }
}

/// A connection that returns its place to the limit when it closes.
struct LimitedConn {
    inner: TcpStream,
    _permit: OwnedSemaphorePermit,
}

impl Connected for LimitedConn {
    type ConnectInfo = ();
    fn connect_info(&self) -> Self::ConnectInfo {}
}

impl AsyncRead for LimitedConn {
    fn poll_read(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buf: &mut ReadBuf<'_>,
    ) -> Poll<std::io::Result<()>> {
        Pin::new(&mut self.inner).poll_read(cx, buf)
    }
}

impl AsyncWrite for LimitedConn {
    fn poll_write(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buf: &[u8],
    ) -> Poll<std::io::Result<usize>> {
        Pin::new(&mut self.inner).poll_write(cx, buf)
    }
    fn poll_flush(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<std::io::Result<()>> {
        Pin::new(&mut self.inner).poll_flush(cx)
    }
    fn poll_shutdown(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<std::io::Result<()>> {
        Pin::new(&mut self.inner).poll_shutdown(cx)
    }
}

/// The bearer-token check: every call, including `Watch()`, carries `authorization: Bearer <token>`.
fn token_interceptor(
    token: Option<String>,
) -> impl FnMut(Request<()>) -> Result<Request<()>, Status> + Clone {
    move |request: Request<()>| {
        let Some(expected) = &token else {
            return Ok(request);
        };
        let given = request
            .metadata()
            .get("authorization")
            .and_then(|v| v.to_str().ok())
            .and_then(|v| v.strip_prefix("Bearer "));
        match given {
            Some(g) if crate::hmac::constant_time_eq(g.as_bytes(), expected.as_bytes()) => {
                Ok(request)
            }
            _ => Err(Status::unauthenticated("missing or wrong bearer token")),
        }
    }
}

/// A running health service. Dropping it does not stop it; `stop()` does.
// The binary never stops the service before it exits (the handle only keeps it alive); `stop` is for the tests.
#[cfg_attr(not(test), allow(dead_code))]
pub struct Handle {
    pub local_addr: SocketAddr,
    stop: Option<oneshot::Sender<()>>,
    thread: Option<std::thread::JoinHandle<()>>,
}

#[cfg_attr(not(test), allow(dead_code))]
impl Handle {
    /// Stops accepting, ends every stream and waits for the service thread.
    pub fn stop(mut self) {
        if let Some(tx) = self.stop.take() {
            let _ = tx.send(());
        }
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

/// Starts the service on its own thread with its own runtime and returns once it is listening
/// (or why it could not).
pub fn spawn(config: HealthGrpcConfig, source: ReportSource) -> Result<Handle, String> {
    let (ready_tx, ready_rx) = std::sync::mpsc::channel::<Result<SocketAddr, String>>();
    let (stop_tx, stop_rx) = oneshot::channel::<()>();
    let thread = std::thread::Builder::new()
        .name("health-grpc".to_string())
        .spawn(move || {
            let runtime = match tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()
            {
                Ok(rt) => rt,
                Err(e) => {
                    let _ = ready_tx.send(Err(format!("health_grpc: runtime: {e}")));
                    return;
                }
            };
            runtime.block_on(run(config, source, ready_tx, stop_rx));
            // streams that are still closing get a moment, then the runtime goes away with its tasks
            runtime.shutdown_timeout(Duration::from_secs(2));
        })
        .map_err(|e| format!("health_grpc: thread: {e}"))?;
    match ready_rx.recv() {
        Ok(Ok(local_addr)) => Ok(Handle {
            local_addr,
            stop: Some(stop_tx),
            thread: Some(thread),
        }),
        Ok(Err(e)) => {
            let _ = thread.join();
            Err(e)
        }
        Err(_) => Err("health_grpc: the service thread ended before it listened".to_string()),
    }
}

async fn run(
    config: HealthGrpcConfig,
    source: ReportSource,
    ready: std::sync::mpsc::Sender<Result<SocketAddr, String>>,
    stop: oneshot::Receiver<()>,
) {
    let listener = match tokio::net::TcpListener::bind(config.listen).await {
        Ok(l) => l,
        Err(e) => {
            let _ = ready.send(Err(format!(
                "health_grpc: cannot listen on {}: {e}",
                config.listen
            )));
            return;
        }
    };
    let local_addr = match listener.local_addr() {
        Ok(a) => a,
        Err(e) => {
            let _ = ready.send(Err(format!("health_grpc: {e}")));
            return;
        }
    };
    let (shutdown_tx, shutdown_rx) = tokio::sync::watch::channel(false);
    let limit = Arc::new(Semaphore::new(config.max_connections.max(1)));
    let (conn_tx, conn_rx) = mpsc::channel::<Result<LimitedConn, std::io::Error>>(1);
    // the accept loop: a connection past the limit is closed at once instead of queued
    let accept_limit = Arc::clone(&limit);
    let mut accept_shutdown = shutdown_rx.clone();
    let accept = tokio::spawn(async move {
        loop {
            let accepted = tokio::select! {
                a = listener.accept() => a,
                _ = accept_shutdown.changed() => break,
            };
            match accepted {
                Ok((socket, _)) => match Arc::clone(&accept_limit).try_acquire_owned() {
                    Ok(permit) => {
                        let _ = socket.set_nodelay(true);
                        let conn = LimitedConn {
                            inner: socket,
                            _permit: permit,
                        };
                        if conn_tx.send(Ok(conn)).await.is_err() {
                            break;
                        }
                    }
                    Err(_) => drop(socket),
                },
                Err(_) => tokio::time::sleep(Duration::from_millis(50)).await,
            }
        }
    });

    let service = Service {
        source,
        watchers: Arc::new(AtomicUsize::new(0)),
        max_watchers: config.max_watchers,
        interval: config.watch_interval,
        shutdown: shutdown_rx,
    };
    let svc = tonic::service::interceptor::InterceptedService::new(
        HealthServiceServer::new(service)
            .max_decoding_message_size(1024)
            .max_encoding_message_size(64 * 1024),
        token_interceptor(config.token.clone()),
    );
    let _ = ready.send(Ok(local_addr));
    let result = tonic::transport::Server::builder()
        .http2_keepalive_interval(Some(config.keepalive))
        .http2_keepalive_timeout(Some(config.keepalive))
        .max_concurrent_streams(Some((config.max_watchers as u32).saturating_add(8)))
        .add_service(svc)
        .serve_with_incoming_shutdown(ReceiverStream::new(conn_rx), async {
            let _ = stop.await;
            let _ = shutdown_tx.send(true);
        })
        .await;
    if let Err(e) = result {
        crate::log_line!("health_grpc: the service ended with an error: {e}");
    }
    accept.abort();
}

#[cfg(test)]
mod tests {
    use super::pb::health_service_client::HealthServiceClient;
    use super::*;
    use std::sync::atomic::AtomicBool;
    use std::time::Instant;

    fn config(token: Option<&str>) -> HealthGrpcConfig {
        HealthGrpcConfig {
            listen: "127.0.0.1:0".parse().unwrap(),
            token: token.map(str::to_string),
            max_connections: 4,
            max_watchers: 2,
            watch_interval: Duration::from_millis(200),
            keepalive: Duration::from_secs(5),
        }
    }

    fn fixed(state: HealthState) -> ReportSource {
        Arc::new(move || HealthReport {
            identity: Some(identity()),
            state: state as i32,
            detail: "fixed".to_string(),
            metrics: Default::default(),
        })
    }

    fn rt() -> tokio::runtime::Runtime {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
    }

    async fn client(addr: SocketAddr) -> HealthServiceClient<tonic::transport::Channel> {
        HealthServiceClient::connect(format!("http://{addr}"))
            .await
            .unwrap()
    }

    fn with_token<T>(message: T, token: &str) -> Request<T> {
        let mut request = Request::new(message);
        request
            .metadata_mut()
            .insert("authorization", format!("Bearer {token}").parse().unwrap());
        request
    }

    #[test]
    fn check_answers_the_real_report_over_a_real_connection() {
        let handle = spawn(config(None), fixed(HealthState::Ok)).unwrap();
        let addr = handle.local_addr;
        rt().block_on(async {
            let mut c = client(addr).await;
            let r = c.check(Empty {}).await.unwrap().into_inner();
            assert_eq!(r.state, HealthState::Ok as i32);
            let id = r.identity.unwrap();
            assert_eq!(id.name, NODE_NAME);
            assert_eq!(id.version, env!("CARGO_PKG_VERSION"));
        });
        handle.stop();
    }

    #[test]
    fn the_state_follows_the_registry_and_the_global_stop() {
        let registry = Mutex::new(MissionRegistry::new());
        registry.lock().unwrap().add("m-1");
        let r = report(&registry, false);
        assert_eq!(r.state, HealthState::Ok as i32);
        assert_eq!(r.metrics["missions"], "1");
        assert_eq!(r.metrics["missions_active"], "1");
        let r = report(&registry, true);
        assert_eq!(r.state, HealthState::Degraded as i32);
        assert!(r.detail.contains("global stop"));
        // a registry whose lock is poisoned cannot do its job
        let poisoned = Arc::new(Mutex::new(MissionRegistry::new()));
        let p = Arc::clone(&poisoned);
        let _ = std::thread::spawn(move || {
            let _guard = p.lock().unwrap();
            panic!("poison the lock on purpose");
        })
        .join();
        let r = report(&poisoned, false);
        assert_eq!(r.state, HealthState::Unhealthy as i32);
        // a registry that is busy right now is not a failure and the answer does not wait
        let _held = registry.lock().unwrap();
        let started = Instant::now();
        let r = report(&registry, false);
        assert!(started.elapsed() < Duration::from_secs(1));
        assert_eq!(r.state, HealthState::Ok as i32);
        assert!(r.detail.contains("busy"));
    }

    #[test]
    fn watch_sends_at_once_repeats_on_the_interval_and_follows_a_change() {
        let flag = Arc::new(AtomicBool::new(false));
        let f = Arc::clone(&flag);
        let source: ReportSource = Arc::new(move || {
            let state = if f.load(Ordering::SeqCst) {
                HealthState::Unhealthy
            } else {
                HealthState::Ok
            };
            HealthReport {
                identity: Some(identity()),
                state: state as i32,
                detail: String::new(),
                metrics: Default::default(),
            }
        });
        let handle = spawn(config(None), source).unwrap();
        let addr = handle.local_addr;
        rt().block_on(async {
            let mut c = client(addr).await;
            let mut stream = c.watch(Empty {}).await.unwrap().into_inner();
            let started = Instant::now();
            let first = stream.message().await.unwrap().unwrap();
            assert_eq!(first.state, HealthState::Ok as i32);
            assert!(
                started.elapsed() < Duration::from_millis(150),
                "the first report is immediate"
            );
            let repeat = stream.message().await.unwrap().unwrap();
            assert_eq!(
                repeat.state,
                HealthState::Ok as i32,
                "a keepalive repeat while nothing changes"
            );
            flag.store(true, Ordering::SeqCst);
            let changed = tokio::time::timeout(Duration::from_secs(3), async {
                loop {
                    let m = stream.message().await.unwrap().unwrap();
                    if m.state == HealthState::Unhealthy as i32 {
                        return m;
                    }
                }
            })
            .await
            .expect("the change reaches the stream");
            assert_eq!(changed.state, HealthState::Unhealthy as i32);
        });
        handle.stop();
    }

    #[test]
    fn a_token_is_required_when_one_is_set() {
        let handle = spawn(config(Some("s3cret")), fixed(HealthState::Ok)).unwrap();
        let addr = handle.local_addr;
        rt().block_on(async {
            let mut c = client(addr).await;
            let denied = c.check(Empty {}).await.unwrap_err();
            assert_eq!(denied.code(), tonic::Code::Unauthenticated);
            let denied = c.watch(Empty {}).await.unwrap_err();
            assert_eq!(denied.code(), tonic::Code::Unauthenticated);
            let wrong = c.check(with_token(Empty {}, "nope")).await.unwrap_err();
            assert_eq!(wrong.code(), tonic::Code::Unauthenticated);
            assert!(c.check(with_token(Empty {}, "s3cret")).await.is_ok());
            assert!(c.watch(with_token(Empty {}, "s3cret")).await.is_ok());
        });
        handle.stop();
    }

    #[test]
    fn watch_streams_are_limited_and_their_places_come_back() {
        let handle = spawn(config(None), fixed(HealthState::Ok)).unwrap();
        let addr = handle.local_addr;
        rt().block_on(async {
            let mut c = client(addr).await;
            let mut a = c.watch(Empty {}).await.unwrap().into_inner();
            let _b = c.watch(Empty {}).await.unwrap().into_inner();
            // the limit is 2: the third is refused (the refusal arrives as the status of the stream)
            let third = c.watch(Empty {}).await;
            assert_eq!(third.unwrap_err().code(), tonic::Code::ResourceExhausted);
            assert!(a.message().await.unwrap().is_some());
            // closing a stream gives its place back
            drop(a);
            let mut again = None;
            for _ in 0..40 {
                match c.watch(Empty {}).await {
                    Ok(s) => {
                        again = Some(s);
                        break;
                    }
                    Err(_) => tokio::time::sleep(Duration::from_millis(50)).await,
                }
            }
            assert!(
                again.is_some(),
                "the place of a closed stream is free again"
            );
        });
        handle.stop();
    }

    #[test]
    fn connections_past_the_limit_are_closed_and_the_rest_keep_working() {
        let mut cfg = config(None);
        cfg.max_connections = 1;
        let handle = spawn(cfg, fixed(HealthState::Ok)).unwrap();
        let addr = handle.local_addr;
        rt().block_on(async {
            let mut first = client(addr).await;
            assert!(first.check(Empty {}).await.is_ok());
            // the second connection is accepted by the kernel and closed by the service
            let second = tokio::time::timeout(Duration::from_secs(2), async {
                match HealthServiceClient::connect(format!("http://{addr}")).await {
                    Ok(mut c) => c.check(Empty {}).await.is_err(),
                    Err(_) => true,
                }
            })
            .await
            .unwrap_or(true);
            assert!(second, "a second connection does not get an answer");
            assert!(
                first.check(Empty {}).await.is_ok(),
                "the first connection is not affected"
            );
        });
        handle.stop();
    }

    #[test]
    fn stop_ends_the_streams_and_frees_the_port() {
        let handle = spawn(config(None), fixed(HealthState::Ok)).unwrap();
        let addr = handle.local_addr;
        let runtime = rt();
        let mut stream = runtime.block_on(async {
            let mut c = client(addr).await;
            let mut s = c.watch(Empty {}).await.unwrap().into_inner();
            assert!(s.message().await.unwrap().is_some());
            s
        });
        handle.stop();
        runtime.block_on(async {
            let ended = tokio::time::timeout(Duration::from_secs(3), async {
                while let Ok(Some(_)) = stream.message().await {}
            })
            .await;
            assert!(ended.is_ok(), "the stream ends when the service stops");
        });
        assert!(
            std::net::TcpListener::bind(addr).is_ok(),
            "the port is free again"
        );
    }

    #[test]
    fn a_port_in_use_is_reported_not_swallowed() {
        let taken = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
        let mut cfg = config(None);
        cfg.listen = taken.local_addr().unwrap();
        let err = spawn(cfg, fixed(HealthState::Ok)).err().expect("an error");
        assert!(err.contains("cannot listen"), "{err}");
    }
}
